package java_coding_11th_jan;

public class PrintNumbersUsingDoWhile {
    public static void main(String[] args) {
        //Description:
        //Write a Java program to print numbers from 1 to 10 using a do-while loop.
        int n= 1;
        do {
            System.out.println(n);
            n++;
        }while (n<=10);
    }
}
